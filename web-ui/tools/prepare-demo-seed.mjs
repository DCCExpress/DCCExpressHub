import { cp, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webUiRoot = resolve(here, "..");
const repoRoot = resolve(webUiRoot, "..");
const dataRoot = join(repoRoot, "data");
const generatedPath = join(
  webUiRoot,
  "src",
  "demo",
  "demoSeed.generated.ts"
);
const publicImages = join(
  webUiRoot,
  "public",
  "images"
);

async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

async function readJson(path, fallback) {
  if (!(await exists(path))) {
    return fallback;
  }

  return JSON.parse(
    await readFile(path, "utf8")
  );
}

function normalizeLocoImages(locos) {
  if (!Array.isArray(locos)) {
    return [];
  }

  return locos.map(loco => {
    if (
      !loco ||
      typeof loco !== "object"
    ) {
      return loco;
    }

    const next = { ...loco };

    if (
      typeof next.image === "string"
    ) {
      next.image = next.image.replace(
        /^\/+images\//u,
        "images/"
      );
    }

    return next;
  });
}

function signalRulesToJsonl(document) {
  if (
    !document ||
    typeof document !== "object"
  ) {
    return (
      '{"kind":"meta","version":3,"enabled":false}\n'
    );
  }

  const enabled =
    document.enabled === true;

  const lines = [
    JSON.stringify({
      kind: "meta",
      version: 3,
      enabled,
    }),
  ];

  if (Array.isArray(document.groups)) {
    for (const group of document.groups) {
      lines.push(
        JSON.stringify({
          kind: "group",
          group,
        })
      );
    }
  }

  return `${lines.join("\n")}\n`;
}

const layoutPath =
  join(dataRoot, "layout.json");
const locosPath =
  join(dataRoot, "locos.json");
const signalRulesPath =
  join(dataRoot, "signal-rules.json");
const signalRulesJsonlPath =
  join(dataRoot, "signal-rules.jsonl");
const imagesPath =
  join(dataRoot, "images");

const hasAnySeed =
  (await exists(layoutPath)) ||
  (await exists(locosPath)) ||
  (await exists(signalRulesPath)) ||
  (await exists(signalRulesJsonlPath));

if (!hasAnySeed) {
  console.log(
    "[demo-seed] No data/layout.json, data/locos.json or signal rules found; keeping the committed generated seed."
  );
  process.exit(0);
}

const layout = await readJson(
  layoutPath,
  {
    gridSize: 40,
    layers: [],
  }
);

const locos =
  normalizeLocoImages(
    await readJson(
      locosPath,
      []
    )
  );

let signalRulesJsonl =
  '{"kind":"meta","version":3,"enabled":false}\n';

if (
  await exists(signalRulesJsonlPath)
) {
  signalRulesJsonl =
    await readFile(
      signalRulesJsonlPath,
      "utf8"
    );
} else if (
  await exists(signalRulesPath)
) {
  signalRulesJsonl =
    signalRulesToJsonl(
      await readJson(
        signalRulesPath,
        null
      )
    );
}

const source = `// AUTO-GENERATED by tools/prepare-demo-seed.mjs.
// Commit this file so GitHub Pages has demo seed data even when data/*.json
// is excluded from the repository.

export const demoSeedLayout = ${JSON.stringify(layout, null, 2)} as const;

export const demoSeedLocos = ${JSON.stringify(locos, null, 2)} as const;

export const demoSeedSignalRulesJsonl = ${JSON.stringify(signalRulesJsonl)};
`;

await mkdir(
  dirname(generatedPath),
  { recursive: true }
);

await writeFile(
  generatedPath,
  source,
  "utf8"
);

if (await exists(imagesPath)) {
  await mkdir(
    publicImages,
    { recursive: true }
  );

  await cp(
    imagesPath,
    publicImages,
    {
      recursive: true,
      force: true,
    }
  );
}

console.log(
  `[demo-seed] Generated from ${dataRoot}`
);
console.log(
  `[demo-seed] Locomotives: ${locos.length}`
);
console.log(
  `[demo-seed] Layout layers: ${
    Array.isArray(layout.layers)
      ? layout.layers.length
      : 0
  }`
);
